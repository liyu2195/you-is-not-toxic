"""arXiv version: the remaining numbers of the data and labeler appendices, and the population table (no new labels).
Sources: results/x55_placebo/x08_placebo.json and results/x72_placebo/x08_placebo.json (population sizes and gold prevalence, as
x15_paper_numbers.py and x17_data_inline.py print them); data/cc_meta.parquet; results/f10_population.json;
results/f51_items_haiku.parquet; results/second/s5_articles.txt; results/x81/prn.json; results/x14_pops/cc_s5.parquet; the stored
Claude answers (parsed as x09_build_pops.py parses them). Writes paper_arxiv/numbers_arxiv_d.tex (prefix xe) and
paper_arxiv/tables/xe_pops.tex.
usage: python3 x98d_arxiv_numbers.py"""
import os as _os
_ROOT = _os.environ.get("YOU_IS_NOT_TOXIC_ROOT") or _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "..", ".."))  # repository root (release: replaces the workspace path)
import json, glob
import numpy as np, pandas as pd
W = _ROOT; R = f"{W}/results"; M = {}
th = lambda n: f"{int(n):,}".replace(",", "{,}")
pc1 = lambda v: f"{100 * v:.1f}\\%"
P55 = json.load(open(f"{R}/x55_placebo/x08_placebo.json")); P72 = json.load(open(f"{R}/x72_placebo/x08_placebo.json"))
pops = [("CcThreads", P55["cc_threads"]), ("Sfive", P55["cc_threads_s5"]), ("Cad", P55["cad_threads"]), ("Reddit", P55["qian_reddit"]),
        ("Gab", P55["qian_gab"]), ("Cga", P72["cga"]), ("Bad", P55["bad"])]
for tag, p in pops:
    M[f"xePop{tag}N"] = th(p["n_items"]); M[f"xePop{tag}Units"] = th(p["n_units"]); M[f"xePop{tag}Edges"] = th(p["n_edges"]); M[f"xePop{tag}Prev"] = pc1(p["gold_prev"])
# cross-check with the earlier-draft population sentence (tables/data_inline.tex, written by x17_data_inline.py)
inl = open(f"{W}/results/reference/tables/data_inline.tex").read()
for tag, _ in pops:
    for k in ("N", "Units", "Edges"):
        assert M[f"xePop{tag}{k}"] in inl, (tag, k)
M["xeCcFilesN"] = th(len(pd.read_parquet(f"{W}/data/cc_meta.parquet", columns=["id"])))
M["xeCcTrainN"] = th(json.load(open(f"{R}/f10_population.json"))["n_comments_total"])
M["xeCcArticles"] = th(P55["cc_threads"]["avalle"]["articles"]["n_conversations"])
M["xeSfiveFrameArticles"] = th(pd.read_parquet(f"{R}/f51_items_haiku.parquet", columns=["article"]).article.nunique())
M["xeSfiveDrawnArticles"] = th(sum(1 for l in open(f"{R}/second/s5_articles.txt") if l.strip()))
M["xePromptThreads"] = th(json.load(open(f"{R}/x81/prn.json"))["n_threads"])
M["xeSfiveArticles"] = th(P55["cc_threads_s5"]["avalle"]["articles"]["n_conversations"])
M["xeSfiveDropThreads"] = th(json.load(open(f"{R}/x81/prn.json"))["n_threads"] - P55["cc_threads_s5"]["n_units"])
C = pd.read_parquet(f"{W}/data/cga_meta.parquet"); C = C[C.verified.eq(1) & C.pair_verified.eq(1)]
M["xeCgaSelf"] = str(int((C.parent_uid == C.uid).sum()))


def unparsed(d):
    Rr = pd.DataFrame([json.loads(l) for f in sorted(glob.glob(f"{d}/shard_*.jsonl")) for l in open(f)])
    if "error" in Rr:
        Rr = Rr[Rr["error"].isna()]
    Rr = Rr.drop_duplicates("id", keep="last"); return float((~Rr.ans.isin(["A", "B", "C", "D"])).mean())


M["xeHaikuUnparsedNoCtx"] = f"{100 * unparsed(f'{R}/full/haiku_tox_ctx0'):.3f}\\%"; M["xeHaikuUnparsedCtx"] = f"{100 * unparsed(f'{R}/full/haiku_tox_ctx1'):.3f}\\%"
M["xeSonnetUnparsedNoCtx"] = f"{100 * unparsed(f'{R}/second/s5/sonnet_tox_ctx0'):.3f}\\%"; M["xeSonnetUnparsedCtx"] = f"{100 * unparsed(f'{R}/second/s5/sonnet_tox_ctx1'):.3f}\\%"
S5 = pd.read_parquet(f"{R}/x14_pops/cc_s5.parquet", columns=["y:qwen7b_m", "z"])
M["xeQwenFlagSfive"] = f"{100 * np.nanmean(S5['y:qwen7b_m'].values):.2f}\\%"; M["xeGoldPrevSfiveTwo"] = f"{100 * S5.z.mean():.2f}\\%"
# the population table (rows only)
names = [("Civil Comments reply threads", "CcThreads", "news comments", "toxicity", "reply thread"), ("\\quad 5\\% sample", "Sfive", "", "", "reply thread"),
         ("CAD", "Cad", "Reddit", "abuse", "thread"), ("Qian et al.'s Reddit", "Reddit", "Reddit", "hate speech", "conversation"),
         ("Qian et al.'s Gab", "Gab", "Gab", "hate speech", "conversation"), ("CGA-Wiki", "Cga", "Wikipedia talk pages", "personal attack", "conversation"),
         ("BAD", "Bad", "human--chatbot dialogue", "unsafe turn", "dialogue")]
rows = [f"{a} & {c} & {d} & {e} & \\xePop{t}N & \\xePop{t}Units & \\xePop{t}Edges & \\xePop{t}Prev \\\\" for a, t, c, d, e in names]
open(f"{W}/paper_arxiv/tables/xe_pops.tex", "w").write("\n".join(rows) + "\n")
txt = "% generated by scripts/x98d_arxiv_numbers.py; do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in M.items())
open(f"{W}/paper_arxiv/numbers_arxiv_d.tex", "w").write(txt)
for k, v in M.items():
    print(k, "=", v)
