"""v7h (earlier draft) and arXiv: numbers for the corrections found while building the arXiv version (no new labels).
- Contagion of the LLMs shown the parent over edges between replies (results/x99/x99_ctx_replies.json, from x99_ctx_replies.py):
  the range of their reply risk ratios and gold's risk ratio on the same edges.
- Answers without an option letter: Haiku's share on Civil Comments (results/full/haiku_tox_ctx{0,1}), Sonnet's on the 5% sample's
  articles (results/second/s5/sonnet_tox_ctx{0,1}), parsed as x09_build_pops.py parses them (errors dropped, the last answer kept).
- The size of the 5% sample, and CGA-Wiki's self-replies (data/cga_meta.parquet, verified conversations).
- The threads that the 5% sample leaves out because some labeler's answer is missing: the reply-thread comments whose id is in
  results/second/s5_ids.txt (results/f10_population_thread_items.parquet) minus the 5% sample (results/x14_pops/cc_s5.parquet).
Writes paper_v5/numbers_v7_fix.tex and paper_arxiv/numbers_v7_fix.tex (prefix xd).
usage: python3 x99b_draft_numbers.py"""
import os as _os
_ROOT = _os.environ.get("YOU_IS_NOT_TOXIC_ROOT") or _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "..", ".."))  # repository root (release: replaces the workspace path)
import json, glob, math
import numpy as np, pandas as pd
W = _ROOT; M = {}
f2 = lambda v: f"{v:.2f}"
X = json.load(open(f"{W}/results/x99/x99_ctx_replies.json"))
ctx = [("cc_threads", "haiku_ctx"), ("cc_threads", "qwen7b_m_ctx@own"), ("cc_s5", "sonnet_ctx"), ("cc_s5", "gemma_m_ctx@own"),
       ("cc_s5", "olmo2_ctx"), ("cc_s5", "granite_ctx"), ("cc_s5", "llama31_ctx")]
rr = {k: X[p]["labelers"][k]["rr_between_replies"][0] for p, k in ctx}
base = {"haiku_ctx": "haiku", "qwen7b_m_ctx@own": "qwen7b_m", "sonnet_ctx": "sonnet", "gemma_m_ctx@own": "gemma_m",
        "olmo2_ctx": "olmo2", "granite_ctx": "granite", "llama31_ctx": "llama31"}
for p, k in ctx:                                                   # shown the parent, every LLM's risk ratio is below its own without the parent
    assert X[p]["labelers"][k]["rr_between_replies"][0] < X[p]["labelers"][base[k]]["rr_between_replies"][0], k
    assert X[p]["labelers"][k]["fp"] < X[p]["labelers"][base[k]]["fp"], k        # and its false positives cluster less along edges
    assert X[p]["labelers"][k]["rr_between_replies"][2] < X[p]["gold"]["rr_between_replies"][1], k   # and below gold's
M["xdCtxRepRRMin"] = f2(min(rr.values())); M["xdCtxRepRRMax"] = f2(max(rr.values()))
g1, g2 = X["cc_threads"]["gold"]["rr_between_replies"][0], X["cc_s5"]["gold"]["rr_between_replies"][0]
assert f"{g1:.1f}" == f"{g2:.1f}"; M["xdGoldRepRR"] = f"{g1:.1f}"
M["xdGoldRepRRThreads"] = f2(g1); M["xdGoldRepRRSfive"] = f2(g2)
M["xdHaikuRepRR"] = f2(X["cc_threads"]["labelers"]["haiku"]["rr_between_replies"][0]); M["xdHaikuCtxRepRR"] = f2(rr["haiku_ctx"])
M["xdRepEdges"] = f"{X['cc_threads']['n_edges_between_replies']:,}".replace(",", "{,}")


def unparsed(d):
    R = pd.DataFrame([json.loads(l) for f in sorted(glob.glob(f"{d}/shard_*.jsonl")) for l in open(f)])
    if "error" in R:
        R = R[R["error"].isna()]
    R = R.drop_duplicates("id", keep="last"); bad = ~R.ans.isin(["A", "B", "C", "D"])
    return int(bad.sum()), int(len(R))


sh = {}
for tag, d in (("haiku0", "full/haiku_tox_ctx0"), ("haiku1", "full/haiku_tox_ctx1"), ("sonnet0", "second/s5/sonnet_tox_ctx0"), ("sonnet1", "second/s5/sonnet_tox_ctx1")):
    b, n = unparsed(f"{W}/results/{d}"); sh[tag] = b / n; print(tag, b, "of", n, f"{100 * b / n:.3f}%")
up = lambda v: f"{math.ceil(10000 * v) / 100:.2f}\\%"              # rounded up, as an upper bound
M["xdHaikuUnparsedMax"] = up(max(sh["haiku0"], sh["haiku1"])); M["xdSonnetUnparsedMax"] = up(max(sh["sonnet0"], sh["sonnet1"]))
T = pd.read_parquet(f"{W}/results/f10_population_thread_items.parquet", columns=["root"])
ids5 = set(np.loadtxt(f"{W}/results/second/s5_ids.txt", dtype=np.int64).tolist()); T5 = T[T.index.isin(ids5)]
S5 = pd.read_parquet(f"{W}/results/x14_pops/cc_s5.parquet", columns=["id", "unit"])
assert set(S5.id.astype(np.int64)) <= set(T5.index)
dt = T5.root.nunique() - S5.unit.nunique(); dc = len(T5) - len(S5)
print("5% sample: before", len(T5), T5.root.nunique(), "after", len(S5), S5.unit.nunique(), "dropped", dc, dt)
M["xdSfiveDropThreads"] = f"{dt:,}".replace(",", "{,}"); M["xdSfiveDropComments"] = f"{dc:,}".replace(",", "{,}")
M["xdSfiveN"] = f"{len(S5):,}".replace(",", "{,}")
C = pd.read_parquet(f"{W}/data/cga_meta.parquet"); C = C[C.verified.eq(1) & C.pair_verified.eq(1)]
M["xdCgaSelf"] = str(int((C.parent_uid == C.uid).sum()))                       # self-replies, not counted as reply edges (x09_build_pops.py)
txt = "% generated by scripts/x99b_draft_numbers.py; do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in M.items())
for out in (f"{W}/paper_arxiv/numbers_v7_fix.tex", f"{W}/paper_arxiv/numbers_v7_fix.tex"):
    open(out, "w").write(txt)
for k, v in M.items():
    print(k, "=", v)
